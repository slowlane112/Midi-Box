#!/usr/bin/env python3
"""icongen.py - turn assets/*.icn into main/ui/generated/icons.c/.h (compiled into the firmware)."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "assets")
dst = os.path.join(here, "..", "main", "ui", "generated")
os.makedirs(dst, exist_ok=True)
names = sorted(f for f in os.listdir(src) if f.endswith(".icn"))
h = ["/* Generated by tools/icongen.py - do not edit. */", "#pragma once", "#include <stdint.h>", "",
     "typedef struct {", "    uint16_t w, h;", "    const uint8_t *bits;   /* rows MSB first, each row padded to a byte */", "} icon_t;", ""]
c = ["/* Generated by tools/icongen.py - do not edit. */", '#include "icons.h"', ""]
for f in names:
    b = open(os.path.join(src, f), "rb").read()
    w, hh = b[0] | b[1] << 8, b[2] | b[3] << 8
    ident = re.sub(r"[^a-z0-9]", "_", f[:-4].lower())
    data = b[4:4 + ((w + 7) // 8) * hh]
    c.append("static const uint8_t %s_bits[%d] = {" % (ident, len(data)))
    for i in range(0, len(data), 16):
        c.append("    " + ", ".join("0x%02x" % x for x in data[i:i + 16]) + ",")
    c.append("};")
    c.append("const icon_t %s = { %d, %d, %s_bits };" % (ident, w, hh, ident))
    c.append("")
    h.append("extern const icon_t %s;" % ident)
open(os.path.join(dst, "icons.h"), "w").write("\n".join(h) + "\n")
open(os.path.join(dst, "icons.c"), "w").write("\n".join(c) + "\n")
print("%d icons" % len(names))
