#!/usr/bin/env python3
"""
fontgen.py - rasterise a TTF into a 1-bit proportional bitmap font for MIDI Box.

Output:
  - <name>.c / <name>.h : C tables used by the firmware renderer (gfx_text.c)
  - <name>.json          : the same data, used by tools/mockup.py so mockups are pixel-exact

Glyph coverage: ASCII 32..126 plus extras mapped to codes 0x80+ (see EXTRAS).
Use them in C strings as "\x80" etc. (UI_MIDDOT, UI_ELLIPSIS ... in font.h).

Usage:
  fontgen.py <ttf> <pixel_size> <c_name> <out_dir>
"""
import json, os, sys
from PIL import Image, ImageDraw, ImageFont

EXTRAS = [  # (code, unicode char, C macro name)
    (0x80, "·", "UI_MIDDOT"),
    (0x81, "…", "UI_ELLIPSIS"),
    (0x82, "°", "UI_DEGREE"),
    (0x83, "–", "UI_ENDASH"),
    (0x84, "▼", "UI_DOWN"),
    (0x85, "▲", "UI_UP"),
]


def rasterise(ttf, size):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    line_h = ascent + descent
    chars = [(c, chr(c)) for c in range(32, 127)] + [(c, u) for c, u, _ in EXTRAS]
    glyphs = {}
    for code, ch in chars:
        adv = int(round(font.getlength(ch)))
        img = Image.new("1", (adv + size * 2, line_h + size), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"
        d.text((size, 0), ch, font=font, fill=1)
        bbox = img.getbbox()
        if bbox is None:
            glyphs[code] = dict(adv=adv, x=0, y=0, w=0, h=0, rows=[])
            continue
        x0, y0, x1, y1 = bbox
        rows = []
        for yy in range(y0, y1):
            rows.append("".join("1" if img.getpixel((xx, yy)) else "0" for xx in range(x0, x1)))
        glyphs[code] = dict(adv=adv, x=x0 - size, y=y0, w=x1 - x0, h=y1 - y0, rows=rows)
    return dict(line_h=line_h, ascent=ascent, glyphs=glyphs)


def pack_rows(rows, w):
    """Pack glyph bits row-major, MSB first, continuous bitstream (no row padding)."""
    bits = "".join(rows)
    out = []
    for i in range(0, len(bits), 8):
        chunk = bits[i:i + 8].ljust(8, "0")
        out.append(int(chunk, 2))
    return out


def emit_c(font, cname, out_dir, src_desc):
    data = []
    entries = []
    for code in sorted(font["glyphs"]):
        g = font["glyphs"][code]
        off = len(data)
        data += pack_rows(g["rows"], g["w"])
        entries.append((code, off, g))
    first, last = 32, max(font["glyphs"])
    lines = []
    lines.append("/* Generated by tools/fontgen.py from %s - do not edit. */" % src_desc)
    lines.append('#include "font.h"\n')
    lines.append("static const uint8_t %s_bitmap[%d] = {" % (cname, max(1, len(data))))
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};\n")
    lines.append("static const font_glyph_t %s_glyphs[%d] = {" % (cname, last - first + 1))
    by_code = {c: (o, g) for c, o, g in entries}
    for code in range(first, last + 1):
        if code in by_code:
            o, g = by_code[code]
            ch = chr(code) if 32 <= code < 127 and chr(code) not in "\\'" else "?"
            lines.append("    { %5d, %2d, %2d, %3d, %3d, %3d }, /* 0x%02x %s */" % (o, g["w"], g["h"], g["x"], g["y"], g["adv"], code, ch))
        else:
            lines.append("    {     0,  0,  0,   0,   0,   0 }, /* 0x%02x unused */" % code)
    lines.append("};\n")
    lines.append("const font_t %s = {" % cname)
    lines.append("    .bitmap = %s_bitmap," % cname)
    lines.append("    .glyphs = %s_glyphs," % cname)
    lines.append("    .first = %d," % first)
    lines.append("    .last = %d," % last)
    lines.append("    .line_height = %d," % font["line_h"])
    lines.append("    .ascent = %d," % font["ascent"])
    lines.append("};")
    with open(os.path.join(out_dir, cname + ".c"), "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    if len(sys.argv) != 5:
        print(__doc__)
        sys.exit(1)
    ttf, size, cname, out_dir = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    os.makedirs(out_dir, exist_ok=True)
    font = rasterise(ttf, size)
    emit_c(font, cname, out_dir, "%s @ %dpx" % (os.path.basename(ttf), size))
    js = dict(line_h=font["line_h"], ascent=font["ascent"],
              glyphs={str(k): v for k, v in font["glyphs"].items()})
    with open(os.path.join(out_dir, cname + ".json"), "w") as f:
        json.dump(js, f)
    print("%s: line %d, ascent %d, %d glyphs" % (cname, font["line_h"], font["ascent"], len(font["glyphs"])))


if __name__ == "__main__":
    main()
